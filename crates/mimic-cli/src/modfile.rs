//! `mod.mim`: the automatically managed index of every module and function
//! (inside the project and in its dependencies), with visibility, location
//! and signature hashes, plus a lock of dependency revisions.

use mimic_check::{FnKind, Program};
use mimic_project::{DepSource, MOD_FILE, Project, packages};
use mimic_syntax::config::{self, Table, Value, quote};
use mimic_syntax::{Span, fnv1a};
use std::fs;

fn line_of(src: &str, span: Span) -> i64 {
    let _ = src;
    span.line.max(1) as i64
}

fn entry(k: String, v: Value) -> (String, Value, Span) {
    (k, v, Span::default())
}

pub fn render(project: &Project, p: &Program) -> String {
    let mut out = String::from(
        "module mod\n\n// Generated by mimic — do not edit by hand.\n// Regenerate with `mimic mod update` (check/build/run keep it in sync).\n\n",
    );
    out += &format!("project = {}\n\n", quote(&project.manifest.name));

    let mut modules = Table::default();
    for (mid, m) in p.mods.iter().enumerate() {
        let Some(file) = m.file else { continue };
        let f = &p.files[file];
        let mut t = Table::default();
        t.entries.push(entry("file".into(), Value::Str(f.display.clone())));
        t.entries.push(entry("line".into(), Value::Int(line_of(&f.src, m.span))));
        t.entries.push(entry("pub".into(), Value::Bool(m.is_pub)));
        if m.package != p.root_package {
            t.entries.push(entry("package".into(), Value::Str(m.package.clone())));
        }
        modules.entries.push(entry(p.mod_path(mid).join("::"), Value::Table(t)));
    }
    let mut functions = Table::default();
    for (fid, f) in p.fns.iter().enumerate() {
        let file = &p.files[f.file];
        let sig = f.signature();
        let mut t = Table::default();
        t.entries.push(entry("kind".into(), Value::Ident(if matches!(f.kind, FnKind::Extern { .. }) { "extern" } else { "fn" }.into())));
        t.entries.push(entry("pub".into(), Value::Bool(f.is_pub)));
        t.entries.push(entry("file".into(), Value::Str(file.display.clone())));
        t.entries.push(entry("line".into(), Value::Int(line_of(&file.src, f.span))));
        t.entries.push(entry("sig".into(), Value::Str(sig.clone())));
        t.entries.push(entry("hash".into(), Value::Str(format!("{:016x}", fnv1a(sig.as_bytes())))));
        functions.entries.push(entry(p.fn_path(fid).join("::"), Value::Table(t)));
    }
    let mut lock = Table::default();
    for d in &project.manifest.dependencies {
        let mut t = Table::default();
        match &d.source {
            DepSource::Path(path) => t.entries.push(entry("path".into(), Value::Str(path.display().to_string()))),
            DepSource::Git { url, .. } => t.entries.push(entry("git".into(), Value::Str(url.clone()))),
            DepSource::Installed => t.entries.push(entry("installed".into(), Value::Bool(true))),
        }
        if let Ok(dir) = project.dep_dir(d)
            && let Some(rev) = packages::revision(&dir) {
                t.entries.push(entry("rev".into(), Value::Str(rev)));
            }
        lock.entries.push(entry(d.name.clone(), Value::Table(t)));
    }
    for (name, t) in [("modules", modules), ("functions", functions), ("lock", lock)] {
        out += &format!("{name} {{\n");
        config::write_entries(&t, 4, &mut out);
        out += "}\n\n";
    }
    out.truncate(out.trim_end().len());
    out.push('\n');
    out
}

/// Write mod.mim if its content changed. Returns true when the file was (re)written.
pub fn sync(project: &Project, p: &Program) -> Result<bool, String> {
    let path = project.root.join(MOD_FILE);
    let body = render(project, p);
    if fs::read_to_string(&path).ok().as_deref() == Some(body.as_str()) {
        return Ok(false);
    }
    fs::write(&path, body).map_err(|e| format!("cannot write {}: {e}", path.display()))?;
    Ok(true)
}

/// Rows for `mimic mod list`: (path, kind, pub, location).
pub fn listing(p: &Program, all: bool) -> Vec<(String, &'static str, bool, String)> {
    let mut rows = Vec::new();
    for (mid, m) in p.mods.iter().enumerate() {
        let Some(file) = m.file else { continue };
        if !all && m.package != p.root_package {
            continue;
        }
        rows.push((p.mod_path(mid).join("::"), "module", m.is_pub, format!("{}:{}", p.files[file].display, m.span.line)));
    }
    if all {
        for (fid, f) in p.fns.iter().enumerate() {
            let kind = if matches!(f.kind, FnKind::Extern { .. }) { "extern" } else { "fn" };
            rows.push((p.fn_path(fid).join("::"), kind, f.is_pub, format!("{}:{}", p.files[f.file].display, f.span.line)));
        }
    }
    rows.sort();
    rows
}
